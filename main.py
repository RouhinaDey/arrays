numbers = [10, 20, 30, 40, 50]

# Print the array
print("Array:", numbers)

# Access an element
print("First element:", numbers[0])

# Add an element
numbers.append(60)
print("After adding:", numbers)

# Remove an element
numbers.remove(30)
print("After removing:", numbers)

# Loop through the array
for num in numbers:
    print(num)